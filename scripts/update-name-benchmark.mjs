import {readFile, writeFile} from 'node:fs/promises';

const directory = new URL('../examples/04-struct-union/', import.meta.url);
const files = [
    'name-comparison.h',
    'integer-comparison.h',
    'name-comparison-benchmark.cpp',
    'integer-comparison-benchmark.cpp',
];
const parts = [];
for (const file of files) {
    const source = await readFile(new URL(file, directory), 'utf8');
    parts.push(source
        .replace(/^#pragma once\n/gm, '')
        .replace(/^#include "[^"\n]+"\n/gm, '')
        .replace(/^#include <benchmark\/benchmark.h>\n/gm, '')
        .replace(/^BENCHMARK_MAIN\(\);\n/gm, '')
        .trim());
}
await writeFile(new URL('name-comparison-quick-bench.cpp', directory),
    '// Generated by: node scripts/update-name-benchmark.mjs\n'
    + '// Union type-punning requires a compiler extension; undefined in ISO C++.\n'
    + '#include <benchmark/benchmark.h>\n\n'
    + parts.join('\n\n') + '\n');
